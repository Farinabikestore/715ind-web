export function t(lang, key, vars) {
  let s = (ui[lang] && ui[lang][key]) ?? ui.en[key] ?? ui.es[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replaceAll('{' + k + '}', String(vars[k]));
  return s;
}

// Diccionario reducido que se envía al navegador (solo lo que usan los scripts).
export function clientStrings(lang, prefixes) {
  const out = {};
  const base = { ...ui.es, ...ui.en, ...(ui[lang] || {}) };
  for (const k of Object.keys(base)) {
    if (prefixes.some((p) => k.startsWith(p))) out[k] = base[k];
  }
  return out;
}
